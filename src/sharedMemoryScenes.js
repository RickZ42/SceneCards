export function sharedMemorySceneForCard(card) {
  const word = String(card.expression || '').trim().toLowerCase();
  const scene = sharedMemoryScenes.find(value => value.word === word);
  if (!scene) return null;
  const rule = senseRules[word];
  if (!rule) return scene;
  const context = [card.originalLine, card.sceneContext, card.personalExample].filter(Boolean).join(' ');
  const evidence = context || String(card.meaning || '');
  if (rule.negative && new RegExp(rule.negative, 'i').test(evidence)) return null;
  return new RegExp(rule.positive, 'i').test(evidence) ? scene : null;
}
